#!/usr/bin/env python3
"""Generates plugin/src/data/*.lua from the web app's src/data/*.json.

Usage: scripts/gen-data.py <necromancy-ritual-calculator checkout>

Each JSON file becomes a Lua module returning the same data as a table. Objects keyed by item ID ("227")
get integer keys ([227]), and web-only fields (image URLs) are dropped. Keys are sorted so the output is
stable between runs.
"""

import json
import pathlib
import re
import sys

type Json = dict[str, Json] | list[Json] | str | int | float | bool | None

FILES: list[str] = ["equipment", "glyphs", "inks", "items", "rituals"]
DROP: set[str] = {"image"}
IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
LUA_KEYWORDS = set(
    "and break do else elseif end false for function goto if in local nil not or repeat return then true "
    "until while".split()
)


def lua_string(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)  # JSON string escapes are valid Lua escapes for this data.


def lua_key(k: str) -> str:
    if re.fullmatch(r"-?\d+", k):
        return f"[{int(k)}]"
    if IDENT.match(k) and k not in LUA_KEYWORDS:
        return k
    return f"[{lua_string(k)}]"


def sort_key(k: str) -> tuple[int, int, str]:
    return (0, int(k), "") if re.fullmatch(r"-?\d+", k) else (1, 0, k)


def to_lua(value: Json, indent: int = 0) -> str:
    pad, inner = "    " * indent, "    " * (indent + 1)
    if isinstance(value, dict):
        items = [(k, v) for k, v in value.items() if k not in DROP]
        if not items:
            return "{}"
        lines = [f"{inner}{lua_key(k)} = {to_lua(v, indent + 1)}," for k, v in sorted(items, key=lambda kv: sort_key(kv[0]))]
        return "{\n" + "\n".join(lines) + f"\n{pad}}}"
    if isinstance(value, list):
        if not value:
            return "{}"
        lines = [f"{inner}{to_lua(v, indent + 1)}," for v in value]
        return "{\n" + "\n".join(lines) + f"\n{pad}}}"
    if isinstance(value, bool):
        return "true" if value else "false"
    if value is None:
        return "nil"
    if isinstance(value, (int, float)):
        return repr(value)
    return lua_string(value)


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    source = pathlib.Path(sys.argv[1]) / "src" / "data"
    out = pathlib.Path(__file__).resolve().parent.parent / "plugin" / "src" / "data"
    out.mkdir(parents=True, exist_ok=True)
    for name in FILES:
        data: Json = json.loads((source / f"{name}.json").read_text(encoding="utf-8"))
        header = (
            f"-- Generated by scripts/gen-data.py from the web app's src/data/{name}.json. Don't edit by hand;\n"
            "-- run `make data` instead.\n\n"
        )
        (out / f"{name}.lua").write_text(header + "return " + to_lua(data) + "\n", encoding="utf-8")
        print(f"Wrote plugin/src/data/{name}.lua")


if __name__ == "__main__":
    main()
